// The generated trees must not drift. This suite is the only thing standing
// between a hand-edited src/vendor/ file and a release that silently ships old
// component code, so it drives the real tools twice: once against the repository
// (must pass) and once against a corrupted copy (must fail).
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { COMPONENTS } from '../src/components.js'
import { root } from './helpers.js'

const STAGING = join(root, '..', 'dsh-better-sidebar-left-src', 'components')

function run(script, extra = [], cwd = root) {
  try {
    const stdout = execFileSync(process.execPath, [script, ...extra], { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })
    return { code: 0, stdout }
  } catch (error) {
    return { code: error.status ?? 1, stdout: String(error.stdout || ''), stderr: String(error.stderr || '') }
  }
}

/** A throwaway copy of everything the two tools read and write. */
function scratch() {
  const dir = mkdtempSync(join(tmpdir(), 'dsh-better-sidebar-left-'))
  for (const name of ['vendor.mjs', 'build.mjs', 'head.txt', 'tail.txt', 'tail2.txt']) {
    mkdirSync(join(dir, 'tools'), { recursive: true })
    cpSync(join(root, 'tools', name), join(dir, 'tools', name))
  }
  mkdirSync(join(dir, 'src', 'vendor'), { recursive: true })
  cpSync(join(root, 'src', 'components.js'), join(dir, 'src', 'components.js'))
  cpSync(join(root, 'src', 'sidebar.js'), join(dir, 'src', 'sidebar.js'))
  cpSync(join(root, 'src', 'client.js'), join(dir, 'src', 'client.js'))
  cpSync(join(root, 'src', 'vendor'), join(dir, 'src', 'vendor'), { recursive: true })
  return dir
}

test('src/vendor/ is in sync with the component sources', () => {
  const result = run('tools/vendor.mjs', ['--check'])
  assert.equal(result.code, 0, 'vendor --check failed:\n' + (result.stderr || result.stdout))
})

test('src/client.js is in sync with src/sidebar.js and src/vendor/', () => {
  const result = run('tools/build.mjs', ['--check'])
  assert.equal(result.code, 0, 'build --check failed:\n' + (result.stderr || result.stdout))
})

test('a stale vendored bundle fails the gate', () => {
  const dir = scratch()
  try {
    writeFileSync(join(dir, 'src', 'vendor', 'dsh-session-counts.js'), '// hand-edited\nexport default null\n')
    const result = run(join(dir, 'tools', 'vendor.mjs'), ['--check', '--workspace', STAGING], dir)
    assert.equal(result.code, 1, 'a stale vendored file must fail the gate')
    assert.match(result.stdout, /STALE/)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})

test('a stale host half fails the gate', () => {
  const dir = scratch()
  try {
    const target = join(dir, 'src', 'vendor', 'host', 'dsh-declutter.logic.js')
    assert.equal(existsSync(target), true, 'the host half must be vendored with its sibling module')
    writeFileSync(target, '// hand-edited\nexport const RULES = []\n')
    const result = run(join(dir, 'tools', 'vendor.mjs'), ['--check', '--workspace', STAGING], dir)
    assert.equal(result.code, 1, 'a stale host half must fail the gate')
    assert.match(result.stdout, /STALE/)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})

test('a stale generated bundle fails the gate', () => {
  const dir = scratch()
  try {
    writeFileSync(join(dir, 'src', 'client.js'), '// hand-edited\n')
    const result = run(join(dir, 'tools', 'build.mjs'), ['--check'], dir)
    assert.equal(result.code, 1, 'a stale client bundle must fail the gate')
    assert.match(result.stderr, /stale/)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
})

test('every vendored bundle carries the component version and a source stamp', () => {
  const versions = JSON.parse(readFileSync(join(root, 'src', 'vendor', 'versions.json'), 'utf8'))
  for (const component of COMPONENTS) {
    const path = join(root, 'src', 'vendor', component.id + '.js')
    assert.equal(existsSync(path), true, path + ' is missing')
    const source = readFileSync(path, 'utf8')
    assert.match(source, new RegExp('Source: .*' + component.id + '.*  \\(v' + versions[component.id].replace(/\./g, '\\.') + ', sha256 [0-9a-f]{16}\\)'))
  }
})

test('the generated bundle carries all five factories and this plugin half', () => {
  const source = readFileSync(join(root, 'src', 'client.js'), 'utf8')
  assert.ok(source.startsWith('// dsh-better-sidebar-left - browser half. GENERATED by tools/build.mjs - DO NOT EDIT.'))
  for (const component of COMPONENTS) {
    assert.ok(source.includes('const factory_' + component.id.replace(/-/g, '_') + ' = '), component.id + ' factory missing from the bundle')
  }
  assert.ok(source.includes("id: 'dsh-better-sidebar-left'"))
  assert.ok(source.includes('function SidebarPanel'), 'this plugin page did not make it into the bundle')
})